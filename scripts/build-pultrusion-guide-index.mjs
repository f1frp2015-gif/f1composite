// Keep article bodies out of shared card/navigation imports. Regenerate after editing a guide.
import { writeFileSync } from "node:fs";
import { loadProjectModule } from "./load-project-module.mjs";

const { pultrusionGuides } = loadProjectModule("content/data/pultrusionGuides.ts");
const { pultrusionGuideReviewed } = loadProjectModule("content/data/pultrusionGuideTypes.ts");
const applications = pultrusionGuides.filter((page) => page.kind === "application");
const products = pultrusionGuides.filter((page) => page.kind === "product");
const compact = (page) => ({
  slug: page.slug, name: page.name, title: page.title, description: page.description,
  image: page.image, imageAlt: page.imageAlt,
});
const applicationPages = applications.map((page) => ({
  slug: page.slug, calculator: false, lastModified: pultrusionGuideReviewed,
  title: page.title, shortTitle: page.name, description: page.description,
  h1: page.heading, intro: page.summary, environment: page.scope,
  supplyScope: page.scope, image: page.image, imageAlt: page.imageAlt,
  imageNote: "Application schematic", imageCaption: page.imageCaption,
  recommendedProfiles: page.profiles, resinSystem: page.material,
  standards: page.standards.map((item) => item.name), designChecks: [],
  rfqInputs: page.specification, related: page.related,
}));
const groups = applications.map((page) => ({
  label: page.name, description: page.description, href: `/applications/${page.slug}`,
  products: ["custom"],
  links: page.related.filter((link) => link.href.startsWith("/products/")).slice(0, 2),
}));
const output = `// Generated by scripts/build-pultrusion-guide-index.mjs; do not edit.\nimport type { ApplicationPage } from "@/lib/applicationPages";\n\nexport const specialistApplicationPages: ApplicationPage[] = ${JSON.stringify(applicationPages, null, 2)};\n\nexport const specialistProductIndex = ${JSON.stringify(products.map(compact), null, 2)};\n\nexport const specialistApplicationGroups = ${JSON.stringify(groups, null, 2)};\n`;
const routeIndex = `\nexport const specialistGuideRoutes = ${JSON.stringify(pultrusionGuides.map((page) => `/${page.kind === "application" ? "applications" : "products"}/${page.slug}`), null, 2)};\n`;
writeFileSync(new URL("../content/data/pultrusionGuideIndex.ts", import.meta.url), output + routeIndex);
console.log(`Pultrusion guide index: ${applications.length} applications, ${products.length} products.`);
